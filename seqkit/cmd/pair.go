// pairCmd represents the pair command
var pairCmd = &cobra.Command{
	GroupID: "set",

	Use:   "pair",
	Short: "match up paired-end reads from two FASTA/Q files",
	Long: `match up paired-end reads from two FASTA/Q files

Attention:
1. Orders of headers in the two files should be the same (not shuffled),
   otherwise, it consumes a huge number of memory for buffering reads in memory.
2. Unpaired reads are optional outputted with the flag -u/--save-unpaired.
   Duplicate IDs are paired one-to-one in occurrence order; -u retains all extras.
3. If the flag -O/--out-dir is not given, the output will be saved in the same directory
   of input, with the suffix "paired", e.g., read_1.paired.fq.gz.
   Otherwise, names are kept untouched in the given output directory.
   Both first records are checked before outputs are opened. Existing matching
   outputs are overwritten; -f suppresses the directory warning. Unrelated
   files are retained.
4. Paired gzipped files may be slightly larger than original files, because
   of using a different gzip package/library, don't worry.
5. Each output retains its input format; FASTA and FASTQ mates may be mixed.

Tips:
1. Support for '/1 'and '/2' tags for paired read files generated by platforms like MGI.
   You can simply specify the regular expression for extracting sequence IDs:
     --id-regexp '^(\S+)\/[12]'

`,
	Run: func(cmd *cobra.Command, args []string) {
		config := getConfigs(cmd)
		alphabet := config.Alphabet
		idRegexp := config.IDRegexp

		lineWidth := config.LineWidth
		if !config.LineWidthChanged {
			lineWidth = 0
		}
		fastx.ForcelyOutputFastq = false

		seq.AlphabetGuessSeqLengthThreshold = config.AlphabetGuessSeqLength
		seq.ValidateSeq = false
		runtime.GOMAXPROCS(config.Threads)

		if len(args) > 0 {
			checkError(errors.New("no positional arguments are allowed: " + strings.Join(args, " ")))
		}

		read1 := getFlagString(cmd, "read1")
		read2 := getFlagString(cmd, "read2")
		if read1 == "" || read2 == "" {
			checkError(fmt.Errorf("flag -1/--read1 and -2/--read2 needed"))
		}
		if read1 == read2 {
			checkError(fmt.Errorf("values of flag -1/--read1 and -2/--read2 can not be the same"))
		}

		outdir := getFlagString(cmd, "out-dir")
		force := getFlagBool(cmd, "force")
		saveUnpaired := getFlagBool(cmd, "save-unpaired")

		if outdir == "" {
			outdir = filepath.Dir(read1)
		}

		inputDir, err := resolvedPath(filepath.Dir(read1))
		checkError(err)
		outputDir, err := resolvedPath(outdir)
		checkError(err)
		addSuffix := inputDir == outputDir
		base1, suffix1 := filepathTrimExtension(filepath.Base(read1))
		base2, suffix2 := filepathTrimExtension(filepath.Base(read2))
		outFile1 := filepath.Join(outdir, filepath.Base(read1))
		outFile2 := filepath.Join(outdir, filepath.Base(read2))
		if addSuffix {
			outFile1 = filepath.Join(outdir, base1+".paired"+suffix1)
			outFile2 = filepath.Join(outdir, base2+".paired"+suffix2)
		}
		outFile1U := filepath.Join(outdir, base1+".unpaired"+suffix1)
		outFile2U := filepath.Join(outdir, base2+".unpaired"+suffix2)
		outputs := []string{outFile1, outFile2}
		if saveUnpaired {
			outputs = append(outputs, outFile1U, outFile2U)
		}
		checkOutputFiles([]string{read1, read2}, outputs)
		if force && !addSuffix {
			checkOutputDir([]string{read1, read2}, outdir)
		}

		var reader1, reader2 *fastx.Reader
		var record1, record2 *fastx.Record

		// readers
		reader1, err = fastx.NewReader(alphabet, read1, idRegexp)
		checkError(errors.Wrap(err, read1))
		defer reader1.Close()
		reader2, err = fastx.NewReader(alphabet, read2, idRegexp)
		checkError(errors.Wrap(err, read2))
		defer reader2.Close()

		// Validate both initial records before creating or truncating any output.
		record1, err = reader1.Read()
		checkError(errors.Wrap(err, read1))
		record1 = record1.Clone()
		record2, err = reader2.Read()
		checkError(errors.Wrap(err, read2))
		prepareOutputDir(outdir, force)
		outfh1, err := xopen.Wopen(outFile1)
		checkError(err)
		outfh2, err := xopen.Wopen(outFile2)
		checkError(err)

		// FIFO queues preserve every duplicate and pair the oldest occurrences first.
		pending := [2]map[string][]*fastx.Record{make(map[string][]*fastx.Record), make(map[string][]*fastx.Record)}
		paired := [2]*xopen.Writer{outfh1, outfh2}
		var unpaired [2]*xopen.Writer
		paths := [2]string{outFile1U, outFile2U}
		formats := [2]bool{reader1.IsFastq, reader2.IsFastq}
		var pairs, counts1, counts2 int
		closeAll := func() {
			for _, w := range paired {
				closeOutput(w)
			}
			for _, w := range unpaired {
				if w != nil {
					closeOutput(w)
				}
			}
		}
		consume := func(side int, record *fastx.Record) {
			id := string(record.ID)
			other := 1 - side
			if queue := pending[other][id]; len(queue) > 0 {
				writeFastxRecord(paired[side], record, formats[side], lineWidth)
				writeFastxRecord(paired[other], queue[0], formats[other], lineWidth)
				queue[0] = nil
				if len(queue) == 1 {
					delete(pending[other], id)
				} else {
					pending[other][id] = queue[1:]
				}
				pairs++
			} else {
				pending[side][id] = append(pending[side][id], record.Clone())
			}
		}
		consume(0, record1)
		consume(1, record2)
		readers := [2]*fastx.Reader{reader1, reader2}
		done := [2]bool{}
		for !done[0] || !done[1] {
			for side, reader := range readers {
				if done[side] {
					continue
				}
				record, readErr := reader.Read()
				if readErr == io.EOF {
					done[side] = true
					continue
				}
				if readErr != nil {
					closeAll()
					checkError(errors.Wrap(readErr, []string{read1, read2}[side]))
				}
				consume(side, record)
			}
		}
		if saveUnpaired {
			for side, byID := range pending {
				for _, queue := range byID {
					for _, record := range queue {
						if unpaired[side] == nil {
							unpaired[side], err = xopen.Wopen(paths[side])
							checkError(err)
						}
						writeFastxRecord(unpaired[side], record, formats[side], lineWidth)
						if side == 0 {
							counts1++
						} else {
							counts2++
						}
					}
				}
			}
		}
		closeAll()
		if !config.Quiet {
			log.Infof("%d paired-end reads saved to %s and %s", pairs, outFile1, outFile2)
			if saveUnpaired {
				log.Infof("%d unpaired reads saved to %s", counts1, outFile1U)
				log.Infof("%d unpaired reads saved to %s", counts2, outFile2U)
			}
		}

	},
}

func init() {
	RootCmd.AddCommand(pairCmd)

	pairCmd.Flags().StringP("read1", "1", "", "(gzipped) read1 file")
	pairCmd.Flags().StringP("read2", "2", "", "(gzipped) read2 file")
	pairCmd.Flags().StringP("out-dir", "O", "", "output directory")
	pairCmd.Flags().BoolP("force", "f", false, "overwrite matching output files without the nonempty-directory warning")
	pairCmd.Flags().BoolP("save-unpaired", "u", false, "save unpaired reads if there are")
}
